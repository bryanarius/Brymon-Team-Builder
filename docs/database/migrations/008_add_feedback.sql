-- Bug reports and feature suggestions from players, signed in or not.
CREATE TABLE feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(20) NOT NULL
        CHECK (kind IN ('bug', 'suggestion')),
    status VARCHAR(20) NOT NULL DEFAULT 'new'
        CHECK (status IN ('new', 'accepted', 'done', 'declined')),
    -- NULL for guests. A deleted account keeps its reports, unlinked.
    user_id INTEGER NULL
        REFERENCES users (id) ON DELETE SET NULL,
    -- Optional, so a guest can be asked follow-up questions.
    contact_email VARCHAR(255) NULL,
    summary VARCHAR(120) NOT NULL,
    details TEXT NOT NULL,
    -- Bugs only: what the player expected to happen.
    expected TEXT NULL,
    -- Bugs only: pasted text that reproduces it, e.g. a Showdown team.
    attachment TEXT NULL,
    -- The page the player came from, e.g. /teambuilder.
    page_url VARCHAR(500) NULL,
    user_agent VARCHAR(500) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

-- The admin list filters by status, newest first.
CREATE INDEX idx_feedback_status_created_at
    ON feedback (status, created_at DESC);

