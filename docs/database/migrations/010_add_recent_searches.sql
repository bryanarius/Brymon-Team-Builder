-- Trainers you opened from search, shown under "Recent" when the search box
-- is empty, like Instagram. One row per pair: opening the same trainer
-- again just moves them back to the top (searched_at), and
-- App\Models\RecentSearch keeps only the newest 20 per trainer.
--
-- The UNIQUE (user_id, searched_user_id) index also serves "my recent
-- searches", since every lookup starts with user_id and the list is tiny.
CREATE TABLE recent_searches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL
        REFERENCES users (id) ON DELETE CASCADE DEFERRABLE,
    searched_user_id INTEGER NOT NULL
        REFERENCES users (id) ON DELETE CASCADE DEFERRABLE,
    searched_at TIMESTAMP NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, searched_user_id),
    CHECK (user_id <> searched_user_id)
);

INSERT INTO migrations (filename, applied_at)
VALUES ('010_add_recent_searches.sql', NOW());

COMMIT;
